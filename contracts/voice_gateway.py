"""Application boundary used by voice; implementation belongs to the API layer."""
from typing import Callable, Protocol

from packages.domain.models import Session
from packages.domain.state_machine import Decision


class VoiceGateway(Protocol):
    def session(self, session_id: str) -> Session: ...
    def record(self, session_id: str, kind: str, payload: dict) -> None: ...
    def interrupt(self, session_id: str) -> None: ...
    def abort(self, session_id: str, reason: str) -> Session: ...
    def turn(self, session_id: str, request_id: str, body: dict,
             decide: Callable[[Session], Decision]) -> Session: ...
